// lgpl3 reports whether a part is under the LGPL 3.0, which asks for the GPL 3.0 to be included
// with it.
func lgpl3(parts []part) bool {
	for _, p := range parts {
		for _, f := range p.files {
			if strings.Contains(f.text, "GNU LESSER GENERAL PUBLIC LICENSE") && strings.Contains(f.text, "Version 3") {
				return true
			}
		}
	}
	return false
}

// normalize returns a text as it is printed: UTF-8, LF line endings, no trailing blanks, and
// one final newline. A file that isn't UTF-8 is read as Latin-1, which is what the few old files
// with a © use.
func normalize(text string) []byte {
	if !utf8.ValidString(text) {
		runes := make([]rune, len(text))
		for i := range len(text) {
			runes[i] = rune(text[i])
		}
		text = string(runes)
	}
	text = strings.ReplaceAll(text, "\r\n", "\n")
	lines := strings.Split(text, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight(l, " \t")
	}
	return []byte(strings.TrimSpace(strings.Join(lines, "\n")) + "\n")
}

// buildTags returns the tags that build/build.sh uses for goos/goarch. It asks build.sh, so that
// the tags are defined in one place.
func buildTags(goos, goarch string) (string, error) {
	cmd := exec.Command("bash", "build/build.sh", "--print-tags")
	cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch)
	cmd.Stderr = os.Stderr
	tags, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("build/build.sh --print-tags for %s/%s: %w", goos, goarch, err)
	}
	return strings.TrimSpace(string(tags)), nil
}

// goModules returns the modules that any target links, and Go's standard library.
func goModules() ([]part, error) {
	type mod struct{ path, version, dir string }
	seen := map[string]mod{}
	for _, t := range targets {
		tags, err := buildTags(t.goos, t.goarch)
		if err != nil {
			return nil, err
		}
		cmd := exec.Command("go", "list", "-deps", "-tags", tags, "-f",
			`{{with .Module}}{{if not .Main}}{{with .Replace}}{{.Path}}	{{.Version}}	{{.Dir}}{{else}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}{{end}}{{end}}`, ".")
		cmd.Env = append(os.Environ(), "GOOS="+t.goos, "GOARCH="+t.goarch, "CGO_ENABLED=1")
		cmd.Stderr = os.Stderr
		list, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for %s/%s: %w", t.goos, t.goarch, err)
		}
		for line := range strings.SplitSeq(string(list), "\n") {
			f := strings.Split(line, "\t")
			if len(f) != 3 {
				continue
			}
			// A module replaced by a folder of this repository (tools/nosentry) is our own code.
			if f[1] == "" && (strings.HasPrefix(f[0], "./") || strings.HasPrefix(f[0], "../")) {
				continue
			}
			seen[f[0]+" "+f[1]] = mod{f[0], f[1], f[2]}
		}
	}
	keys := make([]string, 0, len(seen))
	for k := range seen {
		keys = append(keys, k)
	}
	slices.Sort(keys)

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return nil, err
	}
	goversion, err := exec.Command("go", "env", "GOVERSION").Output()
	if err != nil {
		return nil, err
	}
	std, err := filesAt(strings.TrimSpace(string(goroot)))
	if err != nil || len(std) == 0 {
		return nil, fmt.Errorf("Go's own license: %v", err)
	}
	// A patch release of the toolchain doesn't change the license. Naming it by its minor
	// version keeps the file from changing with each CI runner's Go.
	minor := strings.Join(strings.SplitN(strings.TrimSpace(string(goversion)), ".", 3)[:2], ".")
	parts := []part{{label: "The Go standard library (" + minor + ")", files: std}}

	var missing []string
	for _, k := range keys {
		m := seen[k]
		files, err := filesAt(m.dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", k, err)
		}
		if len(files) == 0 {
			missing = append(missing, k)
			continue
		}
		parts = append(parts, part{label: m.path + " " + m.version, files: files})
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("no license file at the root of %s: add its terms by hand", strings.Join(missing, ", "))
	}
	return parts, nil
}

// npmPackages returns the packages that `npm ls --omit=dev` lists, split into those with license
// files and those without.
func npmPackages() ([]part, []bare, error) {
	cmd := exec.Command("npm", "ls", "--omit=dev", "--all", "--parseable")
	cmd.Stderr = os.Stderr
	list, err := cmd.Output()
	if err != nil {
		return nil, nil, fmt.Errorf("npm ls: %w", err)
	}
	root, err := os.Getwd()
	if err != nil {
		return nil, nil, err
	}
	// npm prints physical paths. When run from a symlinked directory (macOS's /tmp is one), the
	// root would otherwise be listed as a package of its own.
	if real, err := filepath.EvalSymlinks(root); err == nil {
		root = real
	}
	var parts []part
	var bares []bare
	seen := map[string]bool{}
	for dir := range strings.SplitSeq(strings.TrimSpace(string(list)), "\n") {
		if dir == "" || dir == root {
			continue
		}
		p, err := readPackage(dir)
		if err != nil {
			return nil, nil, err
		}
		label := p.Name + " " + p.Version
		if seen[label] {
			continue // the same version at another place in node_modules
		}
		seen[label] = true
		files, err := filesAt(dir)
		if err != nil {
			return nil, nil, err
		}
		if len(files) > 0 {
			parts = append(parts, part{label: label, files: files})
			continue
		}
		license := p.license()
		if license == "" {
			return nil, nil, fmt.Errorf("%s declares no license and ships no license file: add its terms by hand", label)
		}
		bares = append(bares, bare{label: label, license: license, author: p.author(), repo: p.repo()})
	}
	slices.SortFunc(parts, func(a, b part) int { return strings.Compare(a.label, b.label) })
	slices.SortFunc(bares, func(a, b bare) int { return strings.Compare(a.label, b.label) })
	return parts, bares, nil
}

type packageJSON struct {
	Name       string          `json:"name"`
	Version    string          `json:"version"`
	License    json.RawMessage `json:"license"`
	Licenses   json.RawMessage `json:"licenses"`
	Author     json.RawMessage `json:"author"`
	Repository json.RawMessage `json:"repository"`
}

func readPackage(dir string) (packageJSON, error) {
	var p packageJSON
	raw, err := os.ReadFile(filepath.Join(dir, "package.json"))
	if err != nil {
		return p, err
	}
	if err := json.Unmarshal(raw, &p); err != nil {
		return p, fmt.Errorf("%s: %w", dir, err)
	}
	if p.Name == "" {
		return p, fmt.Errorf("%s: a package with no name", dir)
	}
	return p, nil
}

// stringOr reads a package.json field that is a string or an object with key.
func stringOr(raw json.RawMessage, key string) string {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s
	}
	var o map[string]any
	if json.Unmarshal(raw, &o) == nil {
		if v, ok := o[key].(string); ok {
			return v
		}
	}
	return ""
}

func (p packageJSON) license() string {
	if l := stringOr(p.License, "type"); l != "" {
		return l
	}
	var list []map[string]any
	if json.Unmarshal(p.Licenses, &list) == nil {
		var types []string
		for _, l := range list {
			if t, ok := l["type"].(string); ok {
				types = append(types, t)
			}
		}
		return strings.Join(types, " OR ")
	}
	return ""
}

func (p packageJSON) author() string { return stringOr(p.Author, "name") }

func (p packageJSON) repo() string {
	r := stringOr(p.Repository, "url")
	r = strings.TrimPrefix(r, "git+")
	return strings.TrimSuffix(r, ".git")
}

// filesAt returns the license files at the root of dir, with their names.
func filesAt(dir string) ([]licensed, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []licensed
	for _, e := range entries {
		if e.IsDir() || !licenseFile.MatchString(e.Name()) {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		if len(bytes.TrimSpace(raw)) == 0 {
			continue
		}
		files = append(files, licensed{name: e.Name(), text: string(raw)})
	}
	return files, nil
}

// Command notices writes public/THIRD_PARTY_NOTICES.txt, which holds the licenses of the
// third-party software that a release of Rclone UI includes. That covers the Go modules linked
// into rcui on every target that build/build.sh builds (with its tags), Go's standard library,
// and the npm packages that the pages are built from. The About section shows the file, and
// build/package.sh puts it in every package. A license text that several parts share is printed
// once.
//
//	go run ./build/notices          # write it
//	go run ./build/notices -check   # fail when it is out of date (CI)
package main

import (
	"bytes"
	"crypto/sha256"
	_ "embed"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"unicode/utf8"
)

const out = "public/THIRD_PARTY_NOTICES.txt"

// gpl3 is the GNU GPL 3.0. The LGPL 3.0 builds on it and asks for it to be shipped alongside
// (https://www.gnu.org/licenses/gpl-3.0.txt).
//
//go:embed gpl-3.0.txt
var gpl3 string

// targets are the GOOS/GOARCH pairs that build/build.sh builds. Each one is listed with the tags
// that build.sh uses for it (see buildTags), because a module that only one target links is
// still shipped.
var targets = []struct{ goos, goarch string }{
	{"darwin", "arm64"},
	{"darwin", "amd64"},
	{"windows", "amd64"},
	{"windows", "arm64"},
	{"linux", "amd64"},
	{"linux", "arm64"},
}

// licenseFile matches a file at the root of a module or package that holds its terms.
var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents|unlicense)([._-].*)?$`)

// A part is one module or package, with the files that hold its terms.
type part struct {
	label string // "github.com/rclone/rclone v1.75.1", "react 18.3.1"
	files []licensed
}

type licensed struct{ name, text string }

// bare is an npm package that declares its license in package.json and ships no file for it.
type bare struct{ label, license, author, repo string }

func main() {
	check := flag.Bool("check", false, "fail when "+out+" is out of date")
	flag.Parse()
	text, err := notices()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	if *check {
		have, err := os.ReadFile(out)
		if err != nil || !bytes.Equal(have, text) {
			fmt.Fprintf(os.Stderr, "notices: %s is out of date: run go run ./build/notices\n", out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(out, text, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func notices() ([]byte, error) {
	own, err := os.ReadFile("LICENSE")
	if err != nil {
		return nil, err
	}
	goParts, err := goModules()
	if err != nil {
		return nil, err
	}
	npmParts, bares, err := npmPackages()
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(`Third-party software in Rclone UI
=================================

Rclone UI is licensed under the Apache License 2.0, printed at the end of this file. It includes
the software listed here, each part under its own license. A license text that several parts
share is printed once, after the list of the parts it covers.

The source of Rclone UI is at https://github.com/rclone/rclone-ui, and the source of each part
at its module path or npm package, in the version named.

This file is generated by ` + "`go run ./build/notices`" + `: don't edit it by hand.

Also in some packages
---------------------

- The AppImage bundles the GTK, WebKitGTK and other system libraries it runs on; their copyright
  files are in its usr/share/doc folder.
- The Windows installer carries Microsoft's WebView2 Runtime bootstrapper, under Microsoft's
  terms for it (https://developer.microsoft.com/microsoft-edge/webview2/).

`)
	section(&b, "Go modules linked into rcui", goParts)
	section(&b, "npm packages the pages are built from", npmParts)
	bareSection(&b, bares)
	if lgpl3(goParts) || lgpl3(npmParts) {
		b.WriteString(rule + "The GNU General Public License 3.0, which the LGPL 3.0 above builds on\n\n")
		b.Write(normalize(gpl3))
		b.WriteString("\n")
	}
	b.WriteString(rule + "Rclone UI's own license (LICENSE)\n\n")
	b.Write(normalize(string(own)))
	return b.Bytes(), nil
}

const rule = "================================================================================\n"

// section prints parts grouped by license text. Each text is printed once, after the parts that
// it covers.
func section(b *bytes.Buffer, title string, parts []part) {
	fmt.Fprintf(b, "%s\n%s\n\n", title, strings.Repeat("-", len(title)))
	type group struct {
		text  []byte
		users []string
	}
	groups := map[[32]byte]*group{}
	var order [][32]byte
	for _, p := range parts {
		for _, f := range p.files {
			text := normalize(f.text)
			key := sha256.Sum256(text)
			g, ok := groups[key]
			if !ok {
				g = &group{text: text}
				groups[key] = g
				order = append(order, key)
			}
			g.users = append(g.users, fmt.Sprintf("%s (%s)", p.label, f.name))
		}
	}
	for _, key := range order {
		g := groups[key]
		b.WriteString(rule)
		for _, u := range g.users {
			fmt.Fprintf(b, "%s\n", u)
		}
		b.WriteString("\n")
		b.Write(g.text)
		b.WriteString("\n")
	}
}

// bareSection lists the npm packages that have no license file, grouped by the license that
// their package.json declares. It adds the permission text that the common licenses ask to keep.
func bareSection(b *bytes.Buffer, bares []bare) {
	if len(bares) == 0 {
		return
	}
	title := "npm packages that ship no license file"
	fmt.Fprintf(b, "%s\n%s\n\nThese declare their license in package.json only; their authors hold the copyright.\n\n",
		title, strings.Repeat("-", len(title)))
	byLicense := map[string][]bare{}
	for _, p := range bares {
		byLicense[p.license] = append(byLicense[p.license], p)
	}
	licenses := make([]string, 0, len(byLicense))
	for l := range byLicense {
		licenses = append(licenses, l)
	}
	slices.Sort(licenses)
	for _, l := range licenses {
		b.WriteString(rule)
		fmt.Fprintf(b, "Declared as %s:\n", l)
		for _, p := range byLicense[l] {
			line := p.label
			if p.author != "" {
				line += ", by " + p.author
			}
			if p.repo != "" {
				line += ", " + p.repo
			}
			fmt.Fprintf(b, "%s\n", line)
		}
		// A compound declaration such as "(Apache-2.0 AND BSD-3-Clause)" gets the text of each.
		for _, id := range licenseID.FindAllString(l, -1) {
			if t, ok := permission[id]; ok {
				b.WriteString("\n" + t)
			}
		}
		b.WriteString("\n")
	}
}


// Command gen writes icons_gen.go. For every Name in icons.go, it stores the regular variant of
// that Zappicon glyph as an SVG document. It reads the variant's ES module (the paths' `d` and
// fill rule) and adds the same half-unit stroke that the pages' global.css adds, so the
// launcher's glyphs have the same weight as the pages' icons.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	nameRE = regexp.MustCompile(`Name = "([a-z0-9-]+)"`)
	elRE   = regexp.MustCompile(`\{[^}]*\}`)
	dRE    = regexp.MustCompile(`d: "([^"]+)"`)
)

func main() {
	// go generate runs in app/launcher/icons.
	src, err := os.ReadFile("icons.go")
	check(err)
	seen := map[string]bool{}
	var names []string
	for _, m := range nameRE.FindAllSubmatch(src, -1) {
		if n := string(m[1]); !seen[n] {
			seen[n] = true
			names = append(names, n)
		}
	}
	sort.Strings(names)
	variants := filepath.Join("..", "..", "..", "node_modules", "@zappicon", "react", "dist", "variants")

	var b bytes.Buffer
	b.WriteString("// Code generated by gen from @zappicon/react; DO NOT EDIT.\n\npackage icons\n\nvar svgs = map[Name]string{\n")
	for _, n := range names {
		doc, err := svg(filepath.Join(variants, n+".es.js"))
		check(err)
		fmt.Fprintf(&b, "\t%q: %q,\n", n, doc)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	check(err)
	check(os.WriteFile("icons_gen.go", out, 0o644))
}

// svg returns the regular variant of the glyph in module file f.
func svg(f string) (string, error) {
	src, err := os.ReadFile(f)
	if err != nil {
		return "", err
	}
	s := string(src)
	i := strings.Index(s, `["regular",`)
	if i < 0 {
		return "", fmt.Errorf("%s: no regular variant", f)
	}
	s = s[i:]
	// the variant ends where the next one starts
	if j := strings.Index(s[1:], "\n  [\""); j >= 0 {
		s = s[:j+1]
	}
	var b strings.Builder
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24">`)
	paths := 0
	for _, e := range elRE.FindAllString(s, -1) {
		d := dRE.FindStringSubmatch(e)
		if d == nil {
			continue
		}
		rule := "nonzero"
		if strings.Contains(e, `fillRule: "evenodd"`) {
			rule = "evenodd"
		}
		fmt.Fprintf(&b, `<path fill="#000" fill-rule="%s" stroke="#000" stroke-width="0.5" stroke-linejoin="round" d="%s"/>`, rule, d[1])
		paths++
	}
	if paths == 0 {
		return "", fmt.Errorf("%s: no paths in the regular variant", f)
	}
	b.WriteString(`</svg>`)
	return b.String(), nil
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}
